"""
Writes Symbol.cs: an enum member for every icon in the Material Symbols fonts, named as Jetpack Compose names them
(arrow_back -> ArrowBack, 3d_rotation -> _3dRotation) and valued with the icon's codepoint.

  python make_symbols.py names.tsv ../../src/OsuXaml.Material3/Foundation/Symbol.cs
"""

import sys


def member(name):
    pascal = ''.join(part[:1].upper() + part[1:] for part in name.split('_') if part)
    return '_' + pascal if pascal[0].isdigit() else pascal


def main(names_path, out_path):
    seen = {}
    rows = []

    with open(names_path) as f:
        for line in f:
            name, codepoint = line.split()
            m = member(name)

            if m in seen:
                print(f'skipping {name}: {m} is already {seen[m]}', file=sys.stderr)
                continue

            seen[m] = name
            rows.append((m, name, codepoint))

    with open(out_path, 'w', newline='\n') as f:
        f.write('// <auto-generated>Made by tools/fonts/make_symbols.py from the Material Symbols font; do not edit.</auto-generated>\n\n')
        f.write('namespace OsuXaml.Material3\n{\n')
        f.write('    /// <summary>\n')
        f.write(f'    /// The {len(rows)} Material Symbols icons (fonts.google.com/icons), named as Jetpack Compose names them: <c>arrow_back</c> is\n')
        f.write('    /// <see cref="ArrowBack"/>, <c>3d_rotation</c> is <c>_3dRotation</c>. Each value is the icon\'s codepoint in the font.\n')
        f.write('    /// </summary>\n')
        f.write('    public enum Symbol\n    {\n')
        f.write('        None = 0,\n')
        for m, name, codepoint in rows:
            f.write(f'        {m} = 0x{codepoint.upper()},\n')
        f.write('    }\n}\n')

    print(f'{len(rows)} symbols')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
